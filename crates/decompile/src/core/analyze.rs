use std::{fmt::Display, time::Instant};

use futures::future::BoxFuture;
use heimdall_vm::ext::exec::{TraceDetails, TraceEnd, VMTrace};
use tracing::debug;

use crate::{
    core::{
        control_flow::{
            constant_truthiness, is_bare_reverting, prune_constant_branches_with_details,
        },
        ir::{Expr, Statement},
        memory::MemoryProvenance,
    },
    interfaces::AnalyzedFunction,
    utils::heuristics::{
        argument_heuristic, event_heuristic, extcall_heuristic, modifier_heuristic,
        solidity_heuristic, yul_heuristic, Heuristic,
    },
    Error,
};

/// The type of analyzer to use. This will determine which heuristics are used when analyzing a
/// [`VMTrace`] generated by symbolic execution.
#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub(crate) enum AnalyzerType {
    /// Analyze the trace using Solidity heuristics, which will generate high-level Solidity code
    Solidity,
    /// Analyze the trace using Yul heuristics, which will generate verbose Yul code
    Yul,
    /// Analyze the trace using bare ABI heuristics, which will only generate ABI definitions
    Abi,
}

impl AnalyzerType {
    pub(crate) fn from_args(solidity: bool, yul: bool) -> Self {
        if solidity {
            return AnalyzerType::Solidity;
        }
        if yul {
            return AnalyzerType::Yul;
        }

        AnalyzerType::Abi
    }
}

impl Display for AnalyzerType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AnalyzerType::Solidity => write!(f, "Solidity"),
            AnalyzerType::Yul => write!(f, "Yul"),
            AnalyzerType::Abi => write!(f, "ABI (bare)"),
        }
    }
}

/// State shared between heuristics
#[derive(Debug, Clone)]
pub(crate) struct AnalyzerState {
    /// If we reach a JUMPI, this will hold the conditional for scope tracking
    pub jumped_conditional: Option<Expr>,
    /// Tracks a stack of conditionals, used for scope tracking
    pub conditional_stack: Vec<Expr>,
    /// Tracks which analyzer type we are using
    pub analyzer_type: AnalyzerType,
    /// Whether to skip resolving internal calls
    pub skip_resolving: bool,
    /// Concrete memory bytes established along this execution path.
    pub memory_provenance: MemoryProvenance,
}

/// The analyzer, which will analyze a [`VMTrace`] generated by symbolic execution and build an
/// [`AnalyzedFunction`] based on trace heuristics and opcode analysis.
///
/// Depending on [`AnalyzerType`], the analyzer will use different heuristics to analyze the trace.
pub(crate) struct Analyzer {
    /// The type of analyzer to use
    typ: AnalyzerType,
    /// Whether to skip resolving internal calls
    skip_resolving: bool,
    /// The function to build during analysis
    function: AnalyzedFunction,
    /// A list of registered heuristics with the Heuristic Trait
    heuristics: Vec<Heuristic>,
}

impl Analyzer {
    /// Build a new analyzer with the given type, function, and trace
    pub(crate) fn new(typ: AnalyzerType, skip_resolving: bool, function: AnalyzedFunction) -> Self {
        Self { typ, function, skip_resolving, heuristics: Vec::new() }
    }

    /// Register heuristics for the given function and trace
    pub(crate) fn register_heuristics(&mut self) -> Result<(), Error> {
        match self.typ {
            AnalyzerType::Solidity => {
                self.heuristics.push(Heuristic::new(event_heuristic));
                self.heuristics.push(Heuristic::new(solidity_heuristic));
                self.heuristics.push(Heuristic::new(argument_heuristic));
                self.heuristics.push(Heuristic::new(modifier_heuristic));
                self.heuristics.push(Heuristic::new(extcall_heuristic));
            }
            AnalyzerType::Yul => {
                self.heuristics.push(Heuristic::new(event_heuristic));
                self.heuristics.push(Heuristic::new(yul_heuristic));
                self.heuristics.push(Heuristic::new(argument_heuristic));
                self.heuristics.push(Heuristic::new(modifier_heuristic));
            }
            AnalyzerType::Abi => {
                self.heuristics.push(Heuristic::new(event_heuristic));
                self.heuristics.push(Heuristic::new(argument_heuristic));
                self.heuristics.push(Heuristic::new(modifier_heuristic));
            }
        };

        Ok(())
    }

    /// Performs analysis
    pub(crate) async fn analyze(
        &mut self,
        mut trace_root: VMTrace,
        mut trace_details: TraceDetails,
    ) -> Result<AnalyzedFunction, Error> {
        debug!(
            "analzying symbolic execution trace for '{}' with the {} analyzer",
            self.function.selector, self.typ
        );
        self.function.analyzer_type = self.typ;
        let start_analysis_time = Instant::now();

        // Remove paths made infeasible by identities such as `x == x` before flattening the trace.
        let pruned = prune_constant_branches_with_details(&mut trace_root, &mut trace_details);
        if pruned.paths > 0 {
            debug!(
                "pruned {} infeasible paths across {} constant branches for '{}'",
                pruned.paths, pruned.branches, self.function.selector
            );
        }

        // Register heuristics
        self.register_heuristics()?;

        // get the analyzer state
        let mut analyzer_state = AnalyzerState {
            jumped_conditional: None,
            conditional_stack: Vec::new(),
            analyzer_type: self.typ,
            skip_resolving: self.skip_resolving,
            memory_provenance: MemoryProvenance::default(),
        };

        // Perform analysis
        self.analyze_inner(&trace_root, &trace_details, &mut analyzer_state).await?;

        debug!(
            "analysis for '{}' completed in {:?}",
            self.function.selector,
            start_analysis_time.elapsed()
        );

        Ok(self.function.clone())
    }

    /// Inner analysis implementation
    fn analyze_inner<'a>(
        &'a mut self,
        branch: &'a VMTrace,
        details: &'a TraceDetails,
        analyzer_state: &'a mut AnalyzerState,
    ) -> BoxFuture<'a, Result<(), Error>> {
        Box::pin(async move {
            // reset jumped conditional, we dont propagate conditionals across branches
            analyzer_state.jumped_conditional = None;

            // for each operation in the current trace branch, peform analysis with registerred
            // heuristics
            for operation in &branch.operations {
                analyzer_state.memory_provenance.observe_write(operation);
                for heuristic in &self.heuristics {
                    heuristic.run(&mut self.function, operation, analyzer_state).await?;
                }
                analyzer_state.memory_provenance.observe_call_output(operation);
            }

            // Preserve the taken and fallthrough children as explicit alternatives for Solidity.
            if self.typ == AnalyzerType::Solidity {
                if let Some(state) = branch.operations.last() {
                    let instruction = &state.last_instruction;
                    if instruction.opcode == 0x57 && !branch.children.is_empty() {
                        if branch.children.len() == 1 {
                            let child_edge = details
                                .branches
                                .iter()
                                .find(|edge| edge.child_index == Some(0))
                                .expect("trace details must describe retained children");
                            let child_details = child_edge.details.as_ref();
                            let condition = instruction
                                .input_operations
                                .get(1)
                                .map(Expr::from_opcode)
                                .unwrap_or_else(|| Expr::identifier("unknown_condition"));
                            let fixed_destination = instruction
                                .input_operations
                                .first()
                                .map(Expr::from_opcode)
                                .map(Expr::simplify)
                                .is_some_and(|destination| matches!(destination, Expr::Literal(_)));
                            if let Some(invalid) = details.branches.iter().find(|edge| {
                                fixed_destination &&
                                    edge.child_index.is_none() &&
                                    edge.details.end == TraceEnd::InvalidDestination
                            }) {
                                self.function.push_statement(Statement::If { condition });
                                if !invalid.taken {
                                    self.function.push_statement(Statement::Else);
                                }
                                self.function.push_statement(Statement::Revert(None));
                                self.function.push_statement(Statement::CloseBlock);
                                self.analyze_inner(
                                    &branch.children[0],
                                    child_details,
                                    analyzer_state,
                                )
                                .await?;
                            } else if constant_truthiness(condition.clone()).is_none() &&
                                is_bare_reverting(&branch.children[0])
                            {
                                // The executor can deduplicate the successful sibling while
                                // retaining only its revert path. Preserve the branch as a guard
                                // instead of silently dropping its condition.
                                self.function.push_statement(Statement::If { condition });
                                if !child_edge.taken {
                                    self.function.push_statement(Statement::Else);
                                }
                                let mut revert_state = analyzer_state.clone();
                                self.analyze_inner(
                                    &branch.children[0],
                                    child_details,
                                    &mut revert_state,
                                )
                                .await?;
                                self.function.push_statement(Statement::CloseBlock);
                            } else {
                                self.analyze_inner(
                                    &branch.children[0],
                                    child_details,
                                    analyzer_state,
                                )
                                .await?;
                            }
                            return Ok(());
                        }

                        let alternative = |taken| {
                            details
                                .branches
                                .iter()
                                .find(|edge| edge.taken == taken && edge.child_index.is_some())
                                .and_then(|edge| {
                                    branch
                                        .children
                                        .get(edge.child_index?)
                                        .map(|child| (child, edge.details.as_ref()))
                                })
                        };
                        let taken = alternative(true);
                        let not_taken = alternative(false);

                        if let (
                            Some((taken, taken_details)),
                            Some((not_taken, not_taken_details)),
                        ) = (taken, not_taken)
                        {
                            let condition = instruction
                                .input_operations
                                .get(1)
                                .map(Expr::from_opcode)
                                .unwrap_or_else(|| Expr::identifier("unknown_condition"));

                            // A constant condition that survived pruning means the feasible
                            // child was cut short by jump deduplication and its sibling holds
                            // the rest of the body, so render both sequentially.
                            if let Some(truthiness) = constant_truthiness(condition.clone()) {
                                let incoming_memory = analyzer_state.memory_provenance.clone();
                                let (feasible, feasible_details, sibling, sibling_details) =
                                    if truthiness {
                                        (taken, taken_details, not_taken, not_taken_details)
                                    } else {
                                        (not_taken, not_taken_details, taken, taken_details)
                                    };
                                self.analyze_inner(feasible, feasible_details, analyzer_state)
                                    .await?;
                                analyzer_state.memory_provenance = incoming_memory;
                                self.analyze_inner(sibling, sibling_details, analyzer_state)
                                    .await?;
                                return Ok(());
                            }

                            self.function.push_statement(Statement::If { condition });
                            let mut taken_state = analyzer_state.clone();
                            self.analyze_inner(taken, taken_details, &mut taken_state).await?;
                            self.function.push_statement(Statement::Else);
                            let mut fallthrough_state = analyzer_state.clone();
                            self.analyze_inner(
                                not_taken,
                                not_taken_details,
                                &mut fallthrough_state,
                            )
                            .await?;
                            self.function.push_statement(Statement::CloseBlock);
                            return Ok(());
                        }
                    }
                }

                let incoming_memory = analyzer_state.memory_provenance.clone();
                for (index, child) in branch.children.iter().enumerate() {
                    analyzer_state.memory_provenance = incoming_memory.clone();
                    let child_details = details
                        .branches
                        .iter()
                        .find(|edge| edge.child_index == Some(index))
                        .expect("trace details must describe retained children");
                    self.analyze_inner(child, &child_details.details, analyzer_state).await?;
                }
                return Ok(());
            }

            // Yul continues to use its flat control-flow markers.
            let incoming_memory = analyzer_state.memory_provenance.clone();
            for (index, child) in branch.children.iter().enumerate() {
                analyzer_state.memory_provenance = incoming_memory.clone();
                let child_details = details
                    .branches
                    .iter()
                    .find(|edge| edge.child_index == Some(index))
                    .expect("trace details must describe retained children");
                self.analyze_inner(child, &child_details.details, analyzer_state).await?;
            }

            // check if the ending brackets are needed
            if analyzer_state.jumped_conditional.is_some() &&
                analyzer_state.conditional_stack.contains(
                    analyzer_state.jumped_conditional.as_ref().expect(
                        "impossible case: should have short-circuited in previous conditional",
                    ),
                )
            {
                // remove the conditional
                for (i, conditional) in analyzer_state.conditional_stack.iter().enumerate() {
                    if conditional ==
                        analyzer_state.jumped_conditional.as_ref().expect(
                            "impossible case: should have short-circuited in previous conditional",
                        )
                    {
                        analyzer_state.conditional_stack.remove(i);
                        break;
                    }
                }

                self.function.push_statement(Statement::CloseBlock);
            }

            Ok(())
        })
    }
}

#[cfg(test)]
mod exceptional_jump_tests {
    use super::*;
    use alloy::primitives::Address;
    use heimdall_vm::core::vm::VM;
    use std::time::Duration;

    #[tokio::test]
    async fn invalid_taken_destination_remains_a_conditional_failure() {
        let mut vm = VM::new(
            &[0x34, 0x60, 0x04, 0x57, 0x00],
            &[],
            Address::ZERO,
            Address::ZERO,
            Address::ZERO,
            0,
            u128::MAX,
        );
        let (trace, details, _) =
            vm.symbolic_exec_detailed(Instant::now() + Duration::from_secs(1)).unwrap();
        let function =
            Analyzer::new(AnalyzerType::Solidity, true, AnalyzedFunction::new("fallback", true))
                .analyze(trace, details)
                .await
                .unwrap();
        assert!(function.statements.windows(3).any(|statements| matches!(
            statements,
            [Statement::If { condition }, Statement::Revert(None), Statement::CloseBlock]
                if constant_truthiness(condition.clone()).is_none()
        )));
    }

    #[tokio::test]
    async fn invalid_observed_dynamic_destination_is_not_a_proven_revert() {
        let mut vm = VM::new(
            &[0x34, 0x36, 0x57, 0x00],
            &[],
            Address::ZERO,
            Address::ZERO,
            Address::ZERO,
            0,
            u128::MAX,
        );
        let (trace, details, _) =
            vm.symbolic_exec_detailed(Instant::now() + Duration::from_secs(1)).unwrap();
        let function =
            Analyzer::new(AnalyzerType::Solidity, true, AnalyzedFunction::new("fallback", true))
                .analyze(trace, details)
                .await
                .unwrap();
        assert!(!function
            .statements
            .iter()
            .any(|statement| matches!(statement, Statement::Revert(None))));
    }
}
